// TC-BR-154: the master the partner receives is held as an ordinary
// table carrying the same record shape - the second means of access
// (the alternate key) is a plain index, never a separate store. A pure
// schema fact, verified directly against the live DB - no feed needed.
CASES.push({
  tcId: 'TC-BR-154', rule: 'BR-154',
  run: async () => withDb(async (client) => {
    const results: CheckResult[] = [];
    for (const table of ['contract_record', 'organization_record']) {
      const pk = await client.query(
        `SELECT kcu.column_name FROM information_schema.table_constraints tc
         JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name AND tc.table_schema = kcu.table_schema
         WHERE tc.table_schema = 'adsi_master' AND tc.table_name = $1 AND tc.constraint_type = 'PRIMARY KEY'`,
        [table],
      );
      results.push({
        description: `adsi_master.${table} is an ordinary table keyed on contract_number (not a separate/special store)`,
        pass: pk.rows.length === 1 && pk.rows[0].column_name === 'contract_number',
        detail: JSON.stringify(pk.rows),
      });
    }
    const idx = await client.query(
      `SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = 'adsi_master' AND tablename = 'contract_record' AND indexdef ILIKE '%alternate_key_ssn_or_tin%'`,
    );
    const isPlainNonUniqueIndex = idx.rows.length === 1 && !idx.rows[0].indexdef.toUpperCase().includes('UNIQUE');
    results.push({
      description: 'the alternate key (alternate_key_ssn_or_tin) is a plain, non-unique index - a second means of access into the SAME table, not a separate store',
      pass: isPlainNonUniqueIndex,
      detail: JSON.stringify(idx.rows),
    });
    return results;
  }),
});

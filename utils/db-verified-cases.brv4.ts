// Inserts a fresh, never-used activity_log_entry row directly (mimicking what
// the ingestion pipeline itself would have written), so a later cycle's HR2
// pass has something new to process for a contract/org that already exists in
// pru_adb. Used only for rules that test HR2's downstream routing/counting
// behaviour, never for rules that test the upstream classification decision
// (those require the real ingestion pipeline and are handled separately).
// org_code is generated by the app's own sequence_counter (OFFICE/AGNTINIT),
// not derivable from the allstate_id we minted - must be looked up via the
// real ORG_TO_BD relationship, same join TC-BR-260 verifies directly.
async function orgCodeForBd(client: any, bdAllstateId: string): Promise<string | null> {
  const r = await client.query(
    `SELECT o.org_code FROM pru_adb.contract c
     JOIN pru_adb.node_relationship nr ON nr.child_node_id = c.node_id AND nr.relationship_type = 'ORG_TO_BD'
     JOIN pru_adb.organization o ON o.node_id = nr.parent_node_id
     WHERE c.allstate_id = $1`,
    [bdAllstateId],
  );
  return r.rows[0]?.org_code ?? null;
}

async function insertActivity(
  client: any,
  code: string,
  purposeCode: string,
  subjectId: string,
  transactionCode: string,
  offsetMs = 0,
): Promise<void> {
  await client.query(
    `INSERT INTO pru_adb.activity_log_entry
       (pru_contract_or_org_code, activity_ts, purpose_code, subject_id, transaction_code, crt_by_id)
     VALUES ($1, now() + ($2 || ' milliseconds')::interval, $3, $4, $5, 'CLAUDE01')`,
    [code, String(offsetMs), purposeCode, subjectId, transactionCode],
  );
}


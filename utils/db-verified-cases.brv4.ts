// TC-BR-131: a master write that fails mid-run ends the run WITHOUT a
// completion code being set - status still reads COMPLETED, the master
// row never lands, and master_control.last_updated_date does not advance.
// We force the failure with a narrowly-scoped CHECK constraint on the
// exact SSN minted for this one test (added, then dropped in a finally
// block): blast radius is a single never-otherwise-used value, so no
// other row or writer in the shared database is ever affected.
//
// (A first attempt tried to force this via a genuine pre-existing schema
// mismatch instead - adsi_master.contract_record.crd_number is only 8
// characters wide vs. pru_adb.person.crd_number's 10 - to avoid needing
// any elevated DB permission at all. That did NOT produce a write
// failure: the app silently truncates the oversized value instead of
// rejecting it, which is a real, separate defect worth its own report,

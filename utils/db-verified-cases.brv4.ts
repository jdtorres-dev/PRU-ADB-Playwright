// TC-BR-107: the master record is a record of counted sections - every
// section added is counted three times (within its own kind, within its
// occurrences, and in the record's overall total), and all three must
// agree.
CASES.push({
  tcId: 'TC-BR-107', rule: 'BR-107',
  run: async (console) => {
    const seq = seqFor('BR-107');
    const firm = buildFirm(seq);
    const prod = buildProducer(seq + 1, firm.id.bd, firm.id.bd, 'A');
    const fn = 'ALLSTATE.LNA.BR-107-CANDIDATE.D20260908.txt';
    assembleFile(fn, [[firm.B, firm.C, prod.D1, prod.D2]]);
    const { runId, status } = await uploadAndSettle(console, fn);
    const record = await downloadAndFindAdsimstrRecord(console, runId, prod.id.ssn);
    if (!record) return [{ description: 'the producer\'s record was found in the downloaded ADSIMSTR extract', pass: false, detail: 'not found' }];
    const totSections = ADSIMSTR.totNumOfSections(record.raw);
    const perKind: Array<{ n: number; master: number; occur: number }> = [];
    let sumOccur = 0;
    for (let n = 1; n <= 9; n++) {
      const master = ADSIMSTR.basicMaster(record.raw, n);
      const occur = ADSIMSTR.basicOccur(record.raw, n);
      perKind.push({ n, master, occur });
      sumOccur += occur;
    }
    const allAgree = perKind.every((k) => k.master === k.occur);
    return [
      { description: 'run completed', pass: status === 'COMPLETED', detail: `status=${status}` },
      { description: 'for every BASICn kind, its own MASTER count agrees with its own OCCUR count', pass: allAgree, detail: JSON.stringify(perKind) },
      { description: 'the sum of every kind\'s OCCUR count agrees with the record\'s overall ALL-TOT-NUM-OF-SECTIONS', pass: sumOccur === totSections, detail: `sum(occur)=${sumOccur}, totSections=${totSections}` },
    ];
  },
});

